-- Market Desk on Supabase (project MarketDesk). Run once as the postgres
-- admin. The tables live in their own schema "desk", which the Supabase
-- REST API does not expose: only the two desk logins below can read it.
--   desk_writer  the jobs on the EC2 server (read + write everything)
--   desk_viewer  the Streamlit page (read everything, add / remove alerts)
-- The logins and their passwords are made by market_desk/sql/setup.py.

create schema if not exists desk;
revoke all on schema desk from public;

create table if not exists desk.meta (key text primary key, value text);

create table if not exists desk.verdicts (
  run_ts bigint, market text, rule text, keep integer, why text,
  w_trades integer, w_win double precision, w_exp double precision,
  w_pf double precision, w_dd double precision, w_total double precision,
  c_trades integer, c_win double precision, c_exp double precision,
  c_pf double precision, recent_trades integer, recent_exp double precision);
create index if not exists verdicts_run on desk.verdicts (run_ts);

create table if not exists desk.bt_symbols (
  run_ts bigint, symbol text, market text, scope text, rule text,
  trades integer, win_rate double precision, exp_r double precision,
  pf double precision, total_r double precision, max_dd_r double precision);
create index if not exists bt_symbols_run on desk.bt_symbols (run_ts);

create table if not exists desk.screens (
  run_ts bigint, symbol text, market text, score double precision,
  close double precision, chg_1d double precision, chg_1w double precision,
  chg_1m double precision, rsi double precision, trend text,
  vol_ratio double precision, setups text, notes text, bar_time bigint);
create index if not exists screens_run on desk.screens (run_ts);

create table if not exists desk.plans (
  id bigint generated by default as identity primary key, created_ts bigint,
  symbol text, market text, rule text, entry double precision,
  stop double precision, target double precision, valid_from bigint,
  order_bars integer, score double precision, status text, note text,
  done_ts bigint);
create index if not exists plans_status on desk.plans (status);

create table if not exists desk.trades (
  id bigint generated by default as identity primary key, plan_id bigint,
  symbol text, market text, rule text, entry double precision,
  stop double precision, target double precision, fill_time bigint,
  opened_ts bigint, risk_amt double precision, notional double precision,
  status text, exit double precision, exit_time bigint, closed_ts bigint,
  why text, r double precision, pnl double precision);
create index if not exists trades_status on desk.trades (status);

create table if not exists desk.news (
  link text, symbol text, ts bigint, source text, title text,
  tone double precision, primary key (link, symbol));
create index if not exists news_symbol_ts on desk.news (symbol, ts);

create table if not exists desk.sentiment (
  run_ts bigint, symbol text, market text, headlines_24h integer,
  headlines_7d integer, buzz double precision, tone double precision,
  label text, funding double precision, spike integer);
create index if not exists sentiment_run on desk.sentiment (run_ts);
create index if not exists sentiment_symbol on desk.sentiment (symbol, run_ts);

create table if not exists desk.alerts (
  id bigint generated by default as identity primary key, symbol text,
  op text, price double precision, note text, created_ts bigint,
  fired_ts bigint, fired_px double precision);

-- Written by the server so the cloud page needs no market data of its own
-- (Binance refuses US servers, where Streamlit Cloud runs).
create table if not exists desk.heatmap (
  ts bigint, market text, grp text, label text, symbol text,
  last double precision, chg_1d double precision, chg_1w double precision,
  chg_1m double precision);
create table if not exists desk.quotes (
  symbol text primary key, last double precision,
  change_pct double precision, ts bigint);
